def list_key(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", text.lower())


def collect_toc_entries(doc: Document) -> list[dict[str, str | int]]:
    entries: list[dict[str, str | int]] = []
    for paragraph in doc.paragraphs:
        text = normalized_text(paragraph)
        if not text or text in {"Table of Contents", "Table of Figures", "List of Tables"}:
            continue
        style_name = paragraph.style.name
        if style_name == "Heading 1":
            if text == "List of Acronyms":
                entries.append({"text": "Table of Figures", "level": 1})
                entries.append({"text": "List of Tables", "level": 1})
            entries.append({"text": text, "level": 1})
        elif style_name == "Heading 2":
            entries.append({"text": text, "level": 2})
        elif style_name == "Heading 3":
            entries.append({"text": text, "level": 3})
    return entries


def collect_caption_entries(doc: Document, prefix: str) -> list[dict[str, str | int]]:
    entries: list[dict[str, str | int]] = []
    for paragraph in doc.paragraphs:
        text = normalized_text(paragraph)
        if text.startswith(prefix):
            entries.append({"text": text, "level": 1})
    return entries


def add_static_list_entry(
    anchor: Paragraph,
    text: str,
    page_number: int | None,
    *,
    level: int = 1,
) -> Paragraph:
    paragraph = insert_paragraph_after(anchor)
    paragraph.paragraph_format.left_indent = Inches(0.25 * max(level - 1, 0))
    paragraph.paragraph_format.space_before = Pt(0)
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.paragraph_format.line_spacing = 2.0
    paragraph.paragraph_format.first_line_indent = Inches(0)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
    paragraph.paragraph_format.tab_stops.add_tab_stop(
        Inches(6.5),
        WD_TAB_ALIGNMENT.RIGHT,
        WD_TAB_LEADER.DOTS,
    )
    run = paragraph.add_run(text)
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)
    paragraph.add_run("\t")
    page_run = paragraph.add_run(str(page_number) if page_number is not None else "")
    page_run.font.name = "Times New Roman"
    page_run.font.size = Pt(12)
    return paragraph


def add_static_list_page(
    anchor: Paragraph,
    title: str,
    entries: list[dict[str, str | int]],
    page_numbers: dict[str, int] | None,
    *,
    page_break_before: bool = False,
) -> Paragraph:
    title_para = insert_paragraph_after(anchor)
    style_front_matter_title(title_para, title)
    title_para.paragraph_format.page_break_before = page_break_before
    current = title_para
    for entry in entries:
        text = str(entry["text"])
        current = add_static_list_entry(
            current,
            text,
            page_numbers.get(text) if page_numbers else None,
            level=int(entry.get("level", 1)),
        )
    return current


def rebuild_front_matter_lists(
    doc: Document,
    page_numbers: dict[str, int] | None = None,
) -> None:
    paragraphs = doc.paragraphs
    start = next(
        (
            index
            for index, paragraph in enumerate(paragraphs)
            if normalized_text(paragraph) == "Table of Contents"
        ),
        None,
    )
    acronym_matches = [
        paragraph
        for paragraph in paragraphs
        if normalized_text(paragraph) == "List of Acronyms"
        and paragraph.style.name == "Heading 1"
    ]
    acronym = acronym_matches[-1] if acronym_matches else None
    if start is None or acronym is None:
        raise RuntimeError("Could not locate the front-matter TOC/List of Acronyms boundary.")

    for paragraph in paragraphs[start: paragraphs.index(acronym)]:
        remove_paragraph(paragraph)

    toc_entries = collect_toc_entries(doc)
    figure_entries = collect_caption_entries(doc, "Figure ")
    table_entries = collect_caption_entries(doc, "Table ")

    anchor = insert_paragraph_before(acronym)
    # This empty anchor keeps insertion order stable and is removed after the
    # three generated front-matter pages have been inserted.
    current = add_static_list_page(
        anchor,
        "Table of Contents",
        toc_entries,
        page_numbers,
        page_break_before=False,
    )
    current = add_static_list_page(
        current,
        "Table of Figures",
        figure_entries,
        page_numbers,
        page_break_before=True,
    )
    add_static_list_page(
        current,
        "List of Tables",
        table_entries,
        page_numbers,
        page_break_before=True,
    )
    acronym.paragraph_format.page_break_before = True
    remove_paragraph(anchor)


def split_combined_headings(doc: Document) -> None:
    for paragraph in list(doc.paragraphs):
        text = normalized_text(paragraph)
        for heading, body_start in SPLIT_HEADING_PREFIXES.items():
            marker = f"{heading} {body_start}"
            if text.startswith(marker):
                body = text[len(heading):].strip()
                set_paragraph_text(paragraph, heading)
                body_para = insert_paragraph_after(paragraph, body)
                body_para.style = "Normal"
                break


def apply_heading_styles(doc: Document) -> None:
    chapter_one_seen = False
    for paragraph in doc.paragraphs:
        text = normalized_text(paragraph)
        if text == "Chapter 1 - Introduction":
            chapter_one_seen = True
        if not chapter_one_seen:
            continue
        if not text:
            continue
        if text in {"Table of Contents", "Table of Figures", "List of Tables"}:
            continue
        if text.startswith("Chapter overview."):
            paragraph.style = "Normal"
        elif (
            text == "Abstract"
            or re.match(r"^Chapter\s+\d+(\s|-|:)", text)
            or text in {"References", "REFERENCES", "APPENDICES", "List of Acronyms"}
        ):
            paragraph.style = "Heading 1"
        elif text in {
            "Testing Environment and Reproducibility",
            "Selected Source-Code Evidence",
            "Prompt-template evidence added for camera-ready reproducibility.",
            "Human-effort traceability.",
            "Comparison Discussion",
        }:
            paragraph.style = "Heading 2"
        elif re.match(r"^\d+\.\d+\.\d+", text):
            paragraph.style = "Heading 3"
        elif re.match(r"^\d+\.\d+\s", text):
            paragraph.style = "Heading 2"


def find_paragraph(doc: Document, *texts: str) -> Paragraph:
    wanted = set(texts)
    for paragraph in reversed(doc.paragraphs):
        if normalized_text(paragraph) in wanted:
            return paragraph
    raise RuntimeError(f"Could not locate paragraph: {texts}")


def find_paragraph_starting_with(doc: Document, prefix: str) -> Paragraph:
    for paragraph in reversed(doc.paragraphs):
        if normalized_text(paragraph).startswith(prefix):
            return paragraph
    raise RuntimeError(f"Could not locate paragraph starting with: {prefix}")


def paragraph_index(paragraphs: list[Paragraph], target: Paragraph) -> int:
    for index, paragraph in enumerate(paragraphs):
        if paragraph._p is target._p:
            return index
    raise RuntimeError(f"Paragraph is not present in the document: {normalized_text(target)}")


def move_paragraphs_before(paragraphs: list[Paragraph], anchor: Paragraph) -> None:
    for paragraph in paragraphs:
        anchor._p.addprevious(paragraph._p)


