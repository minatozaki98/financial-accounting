def normalized_text(paragraph: Paragraph) -> str:
    return " ".join(paragraph.text.split())


def iter_blocks(doc: Document) -> list[Paragraph | Table]:
    blocks: list[Paragraph | Table] = []
    for child in doc.element.body.iterchildren():
        if child.tag.endswith("}p"):
            blocks.append(Paragraph(child, doc))
        elif child.tag.endswith("}tbl"):
            blocks.append(Table(child, doc))
    return blocks


def insert_paragraph_before(paragraph: Paragraph, text: str = "") -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addprevious(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if text:
        new_para.add_run(text)
    return new_para


def insert_paragraph_after(paragraph: Paragraph, text: str = "") -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if text:
        new_para.add_run(text)
    return new_para


def insert_caption_before_table(table: Table) -> Paragraph:
    new_p = OxmlElement("w:p")
    table._tbl.addprevious(new_p)
    return Paragraph(new_p, table._parent)


def remove_paragraph(paragraph: Paragraph) -> None:
    parent = paragraph._element.getparent()
    if parent is not None:
        parent.remove(paragraph._element)


def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    paragraph.clear()
    paragraph.add_run(text)


def configure_caption_style(doc: Document) -> None:
    style = doc.styles["Caption"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)
    style.font.bold = False
    style.font.italic = False
    style.paragraph_format.line_spacing = 2.0
    style.paragraph_format.first_line_indent = Inches(0)
    style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fonts = style.element.get_or_add_rPr().get_or_add_rFonts()
    fonts.set(qn("w:eastAsia"), "Times New Roman")
    fonts.set(qn("w:cs"), "Times New Roman")


