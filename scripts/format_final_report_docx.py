def add_hyperlink(paragraph: Paragraph, url: str) -> None:
    relationship_id = paragraph.part.relate_to(url, RT.HYPERLINK, is_external=True)
    hyperlink = OxmlElement("w:hyperlink")
    hyperlink.set(qn("r:id"), relationship_id)
    run = OxmlElement("w:r")
    run_properties = OxmlElement("w:rPr")
    run_style = OxmlElement("w:rStyle")
    run_style.set(qn("w:val"), "Hyperlink")
    run_properties.append(run_style)
    size = OxmlElement("w:sz")
    size.set(qn("w:val"), "24")
    run_properties.append(size)
    complex_size = OxmlElement("w:szCs")
    complex_size.set(qn("w:val"), "24")
    run_properties.append(complex_size)
    run.append(run_properties)
    text = OxmlElement("w:t")
    text.text = url
    run.append(text)
    hyperlink.append(run)
    paragraph._p.append(hyperlink)


def rebuild_references(doc: Document) -> None:
    heading = find_paragraph(doc, "References", "REFERENCES")
    paragraphs = doc.paragraphs
    start = paragraph_index(paragraphs, heading)
    appendix = next(
        (
            paragraph
            for paragraph in paragraphs[start + 1 :]
            if normalized_text(paragraph) == "APPENDICES"
        ),
        None,
    )
    end = paragraph_index(paragraphs, appendix) if appendix is not None else len(paragraphs)
    for paragraph in paragraphs[start + 1 : end]:
        remove_paragraph(paragraph)

    for leading, italicized, trailing, url in REFERENCE_ENTRIES:
        paragraph = insert_paragraph_before(appendix) if appendix is not None else doc.add_paragraph()
        paragraph.style = "Normal"
        paragraph.paragraph_format.left_indent = Inches(0.5)
        paragraph.paragraph_format.first_line_indent = Inches(-0.5)
        paragraph.paragraph_format.space_before = Pt(0)
        paragraph.paragraph_format.space_after = Pt(3)
        paragraph.paragraph_format.line_spacing = 2.0
        paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        leading_run = paragraph.add_run(leading)
        leading_run.font.name = "Times New Roman"
        leading_run.font.size = Pt(12)
        italic_run = paragraph.add_run(italicized)
        italic_run.italic = True
        italic_run.font.name = "Times New Roman"
        italic_run.font.size = Pt(12)
        trailing_run = paragraph.add_run(trailing)
        trailing_run.font.name = "Times New Roman"
        trailing_run.font.size = Pt(12)
        if url:
            add_hyperlink(paragraph, url)


def table_header(table: Table) -> tuple[str, ...]:
    if not table.rows:
        return ()
    return tuple(" ".join(cell.text.split()) for cell in table.rows[0].cells)


def existing_caption_before(blocks: list[Paragraph | Table], table: Table) -> Paragraph | None:
    try:
        index = blocks.index(table)
    except ValueError:
        return None
    if index > 0 and isinstance(blocks[index - 1], Paragraph):
        text = normalized_text(blocks[index - 1])
        if text.startswith(("Figure", "Table")):
            return blocks[index - 1]
    return None


def chapter_from_heading(text: str) -> int | None:
    match = re.match(r"Chapter\s+(\d+)", text)
    if match:
        return int(match.group(1))
    return None


def set_caption(paragraph: Paragraph, text: str, flag: str) -> None:
    paragraph.style = "Caption"
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.keep_with_next = True
    paragraph.paragraph_format.space_before = Pt(6)
    paragraph.paragraph_format.space_after = Pt(4)
    paragraph.paragraph_format.line_spacing = 2.0
    paragraph.paragraph_format.first_line_indent = Inches(0)
    set_paragraph_text(paragraph, text)
    for run in paragraph.runs:
        run.font.name = "Times New Roman"
        run.font.size = Pt(12)
        run.bold = False
        run.italic = False
    add_tc_field(paragraph, text, flag)


def format_data_table(table: Table) -> None:
    try:
        table.style = "Table Grid"
    except KeyError:
        pass
    table.autofit = True
    if table.rows:
        first_row = table.rows[0]
        tr_pr = first_row._tr.get_or_add_trPr()
        if tr_pr.find(qn("w:tblHeader")) is None:
            tr_pr.append(OxmlElement("w:tblHeader"))
        for cell in first_row.cells:
            tc_pr = cell._tc.get_or_add_tcPr()
            shading = tc_pr.find(qn("w:shd"))
            if shading is None:
                shading = OxmlElement("w:shd")
                tc_pr.append(shading)
            shading.set(qn("w:fill"), "D9EAF7")
            for paragraph in cell.paragraphs:
                for run in paragraph.runs:
                    run.bold = True
    for row_index, row in enumerate(table.rows):
        for cell in row.cells:
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.space_before = Pt(0)
                paragraph.paragraph_format.space_after = Pt(0)
                for run in paragraph.runs:
                    run.font.size = Pt(10)
                    run.bold = row_index == 0


def number_table_captions(doc: Document) -> None:
    counters: dict[int, int] = {}
    current_chapter: int | None = None
    blocks = iter_blocks(doc)

    for block in blocks:
        if isinstance(block, Paragraph):
            chapter = chapter_from_heading(normalized_text(block))
            if chapter is not None:
                current_chapter = chapter
            continue

        if current_chapter is None:
            continue

        header = table_header(block)
        title = TABLE_CAPTION_TITLES.get(header)
        if title is None:
            continue

        counters[current_chapter] = counters.get(current_chapter, 0) + 1
        caption_text = f"Table {current_chapter}.{counters[current_chapter]}. {title}"
        caption = existing_caption_before(blocks, block) or insert_caption_before_table(block)
        set_caption(caption, caption_text, "T")
        format_data_table(block)


def number_figure_captions(doc: Document) -> None:
    chapter = 4
    figure_index = 0
    blocks = iter_blocks(doc)
    for index, block in enumerate(blocks):
        if not isinstance(block, Paragraph):
            continue
        text = normalized_text(block)
        previous_is_image = (
            index > 0
            and isinstance(blocks[index - 1], Paragraph)
            and bool(blocks[index - 1]._p.xpath(".//w:drawing"))
        )
        if not text.startswith("Figure 4.") or not previous_is_image:
            continue

        figure_index += 1
        title = text
        while True:
            updated = re.sub(r"^Figure\s+4(?:\.6)?\.\d+\.?\s*", "", title).strip()
            if updated == title:
                break
            title = updated
        caption_text = f"Figure {chapter}.{figure_index}. {title}"
        set_caption(block, caption_text, "F")


def export_pdf(docx_path: Path) -> Path:
    if not SOFFICE.exists():
        raise RuntimeError(f"LibreOffice not found at {SOFFICE}")
    with tempfile.TemporaryDirectory(
        prefix=f"lo-profile-{docx_path.stem}-",
        ignore_cleanup_errors=True,
    ) as profile_name:
        profile = Path(profile_name)
        subprocess.run(
            [
                str(SOFFICE),
                f"-env:UserInstallation=file:///{profile.resolve().as_posix()}",
                "--headless",
                "--convert-to",
                "pdf",
                "--outdir",
                str(docx_path.parent),
                str(docx_path),
            ],
            check=True,
            cwd=ROOT,
        )
    return docx_path.with_suffix(".pdf")


def all_generated_list_entries(doc: Document) -> list[dict[str, str | int]]:
    return (
        collect_toc_entries(doc)
        + collect_caption_entries(doc, "Figure ")
        + collect_caption_entries(doc, "Table ")
    )


def extract_pdf_page_keys(pdf_path: Path) -> list[str]:
    from pypdf import PdfReader

    reader = PdfReader(str(pdf_path))
    page_keys: list[str] = []
    for page in reader.pages:
        page_text = page.extract_text() or ""
        page_keys.append(list_key(page_text))
    return page_keys


def matching_rendered_pages(page_keys: list[str], text: str) -> list[int]:
    key = list_key(text)
    if not key:
        return []

    matches: list[int] = []
    for length in (110, 90, 70, 50, 35, 25):
        needle = key[: min(length, len(key))]
        if not needle:
            continue
        matches = [index + 1 for index, page_key in enumerate(page_keys) if needle in page_key]
        if matches:
            break
    return matches


def find_rendered_page(
    page_keys: list[str],
    text: str,
    body_start_page: int,
) -> int | None:
    matches = matching_rendered_pages(page_keys, text)

    if not matches:
        return None
    if text == "Abstract":
        return min(matches)
    if text in {"Table of Figures", "List of Tables", "List of Acronyms"}:
        front_matter_matches = [page for page in matches if page < body_start_page]
        return max(front_matter_matches) if front_matter_matches else min(matches)

    body_matches = [page for page in matches if page >= body_start_page]
    return min(body_matches) if body_matches else max(matches)


def rendered_page_numbers(pdf_path: Path, doc: Document) -> dict[str, int]:
    page_keys = extract_pdf_page_keys(pdf_path)
    chapter_one_matches = matching_rendered_pages(page_keys, "Chapter 1 - Introduction")
    if not chapter_one_matches:
        raise RuntimeError("Could not locate Chapter 1 in the rendered PDF.")
    body_start_page = max(chapter_one_matches)
    page_numbers: dict[str, int] = {}
    for entry in all_generated_list_entries(doc):
        text = str(entry["text"])
        page_number = find_rendered_page(page_keys, text, body_start_page)
        if page_number is not None:
            page_numbers[text] = page_number
    return page_numbers


def select_word_page(text: str, pages: list[int]) -> int | None:
    if not pages:
        return None
    if text == "Abstract":
        return min(pages)
    return max(pages)


def word_rendered_page_numbers(docx_path: Path, doc: Document) -> tuple[dict[str, int], int]:
    import pythoncom
    import win32com.client

    entries = [str(entry["text"]) for entry in all_generated_list_entries(doc)]
    occurrences: dict[str, list[int]] = {text: [] for text in entries}
    word = None
    word_doc = None
    page_count = 0
    pythoncom.CoInitialize()
    try:
        word = win32com.client.DispatchEx("Word.Application")
        word.Visible = False
        word.DisplayAlerts = 0
        word_doc = word.Documents.Open(
            str(docx_path.resolve()),
            ConfirmConversions=False,
            ReadOnly=True,
            AddToRecentFiles=False,
            Visible=False,
        )
        word_doc.Repaginate()
        content_end = int(word_doc.Content.End)
        for text in entries:
            search_range = word_doc.Content.Duplicate
            previous_end = -1
            while search_range.Find.Execute(
                FindText=text,
                MatchCase=True,
                MatchWholeWord=False,
                MatchWildcards=False,
                Forward=True,
                Wrap=0,
                Format=False,
            ):
                paragraph_text = " ".join(
                    str(search_range.Paragraphs(1).Range.Text)
                    .replace("\x07", " ")
                    .split()
                )
                if paragraph_text == " ".join(text.split()):
                    occurrences[text].append(int(search_range.Information(3)))
                next_start = int(search_range.End)
                if next_start <= previous_end or next_start >= content_end:
                    break
                previous_end = next_start
                search_range.SetRange(next_start, content_end)
        page_count = int(word_doc.ComputeStatistics(2))
    finally:
        if word_doc is not None:
            try:
                word_doc.Close(False)
            except Exception:
                pass
        if word is not None:
            try:
                word.Quit()
            except Exception:
                pass
        word_doc = None
        word = None
        pythoncom.CoUninitialize()

    page_numbers: dict[str, int] = {}
    for text, pages in occurrences.items():
        page = select_word_page(text, pages)
        if page is not None:
            page_numbers[text] = page
    return page_numbers, page_count


def export_pdf_word(docx_path: Path) -> Path:
    import pythoncom
    import win32com.client

    pdf_path = docx_path.with_suffix(".pdf")
    word = None
    word_doc = None
    pythoncom.CoInitialize()
    try:
        word = win32com.client.DispatchEx("Word.Application")
        word.Visible = False
        word.DisplayAlerts = 0
        word_doc = word.Documents.Open(
            str(docx_path.resolve()),
            ConfirmConversions=False,
            ReadOnly=True,
            AddToRecentFiles=False,
            Visible=False,
        )
        word_doc.Fields.Update()
        word_doc.Repaginate()
        word_doc.ExportAsFixedFormat(str(pdf_path.resolve()), 17)
    finally:
        if word_doc is not None:
            word_doc.Close(False)
        if word is not None:
            word.Quit()
        word_doc = None
        word = None
        pythoncom.CoUninitialize()
    return pdf_path


